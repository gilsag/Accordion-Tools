import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const panel = readFileSync("src/components/tools/StradellaChordFinderPanel.tsx", "utf8");
const app = readFileSync("src/App.tsx", "utf8");
const css = readFileSync("src/App.css", "utf8");
assert.match(app, /\| "stradellaRegisters"/);
assert.match(app, /toggleSettingsSection\("stradellaRegisters"\)/);
assert.match(app, /Stradella registers <span>/);
assert.match(app, /activeSettingsSection === "stradellaRegisters"/);
const soundSection = app.indexOf('toggleSettingsSection("sound")');
const registerSection = app.indexOf('toggleSettingsSection("stradellaRegisters")');
assert.ok(registerSection >= 0 && registerSection < soundSection);
assert.equal(app.slice(soundSection, soundSection + 700).includes('Stradella register model (analysis)'), false);
assert.match(panel, /\{showRealizationNote && \(/);
assert.match(panel, /Concise explanation levels/);
assert.doesNotMatch(panel, /<p className="hint">Concise note content/);
assert.doesNotMatch(panel, /<p className="hint">The expanded More explanation/);
assert.match(panel, /className="realization-navigation"/);
assert.match(panel, /aria-label="Previous realization"/);
assert.match(panel, /aria-label="Next realization"/);
assert.match(css, /\.realization-navigation\s*\{/);
assert.match(app, /textAlign: finderFooterEnabled \? "left" : "center"/);
assert.match(app, /line\.slice\(0, colon \+ 1\)/);
console.log("Stradella explanation/settings UI tests passed.");
