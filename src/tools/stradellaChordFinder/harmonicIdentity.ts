/* Harmonic intent is independent of which physical buttons realize it.
   A slash bass is a request about the modeled lowest pitch, NOT a new
   chord formula; Em7/G and Gmaj6 can have identical pitch classes. */
import type { FinderChordPattern } from "../../types";
import { orderedTargetPitches } from "./utils";
import { intervalsForChordFinder } from "../../music/chordDefinitions";
import { finderChordSymbol } from "./chordSymbol";

export type StradellaHarmonicIdentity = {
  root: string;
  pattern: FinderChordPattern;
  /** null = user has not specified an inversion/bass note. */
  requestedBass: string | null;
};

/** Restrict requested inversions to chord tones; no foreign slash-bass
 * additions are generated by this first implementation. */
export function permittedRequestedBasses(root: string, pattern: FinderChordPattern): string[] {
  return orderedTargetPitches(root, pattern);
}

export function validRequestedBass(root: string, pattern: FinderChordPattern, bass: string | null): boolean {
  return bass === null || permittedRequestedBasses(root, pattern).includes(bass);
}

export function harmonicIdentitySymbol(identity: StradellaHarmonicIdentity): string {
  const symbol = finderChordSymbol(identity.root, identity.pattern);
  return identity.requestedBass ? `${symbol}/${identity.requestedBass}` : symbol;
}

export function requestedBassRole(identity: StradellaHarmonicIdentity): string | null {
  const { requestedBass, root, pattern } = identity;
  if (requestedBass === null) return null;
  const position = permittedRequestedBasses(root, pattern).indexOf(requestedBass);
  if (position < 0) return null;
  const semitones = intervalsForChordFinder(pattern)[position];
  if (position === 0) return "root";
  if ([3, 4].includes(semitones)) return "third";
  if (semitones === 5) return "fourth";
  if ([6, 7, 8].includes(semitones)) return "fifth";
  if (semitones === 9) return ["major6", "minor6"].includes(pattern) ? "sixth" : "diminished seventh or sixth";
  if ([10, 11].includes(semitones)) return "seventh";
  if ([13, 14].includes(semitones)) return "ninth";
  if (semitones === 17) return "eleventh";
  if (semitones === 21) return "thirteenth";
  return "extension";
}
